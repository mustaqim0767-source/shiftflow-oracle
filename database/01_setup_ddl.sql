-- Bagian 1: Tabel Master (OUTLETS, USERS, SHIFT_TEMPLATES)
-- ============================================================================

-- 1. Tabel OUTLETS (Cabang / Lokasi Kerja)
CREATE TABLE OUTLETS (
    outlet_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_outlet     VARCHAR2(100) NOT NULL,
    alamat          VARCHAR2(255) NOT NULL,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 2. Tabel USERS (Karyawan & Owner)
CREATE TABLE USERS (
    user_id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    outlet_id           NUMBER NOT NULL,
    nama_lengkap        VARCHAR2(100) NOT NULL,
    email               VARCHAR2(100) NOT NULL UNIQUE,
    password_hash       VARCHAR2(255) NOT NULL,
    role                VARCHAR2(20) DEFAULT 'KARYAWAN' NOT NULL,
    max_jam_mingguan    NUMBER(4,1) DEFAULT 40.0 NOT NULL,
    is_active           NUMBER(1) DEFAULT 1 NOT NULL,
    created_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_users_outlet FOREIGN KEY (outlet_id) REFERENCES OUTLETS(outlet_id),
    CONSTRAINT chk_users_role CHECK (role IN ('KARYAWAN', 'OWNER')),
    CONSTRAINT chk_users_active CHECK (is_active IN (0, 1))
);

-- 3. Tabel SHIFT_TEMPLATES (Master Pola Jam Shift)
CREATE TABLE SHIFT_TEMPLATES (
    template_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_shift      VARCHAR2(50) NOT NULL,
    jam_mulai       VARCHAR2(5) NOT NULL,
    jam_selesai     VARCHAR2(5) NOT NULL,
    durasi_jam      NUMBER(4,1) NOT NULL,
    CONSTRAINT chk_durasi_positif CHECK (durasi_jam > 0)
);

-- Bagian 2: Tabel Transaksi & Audit (SHIFT_SCHEDULES, SHIFT_SWAPS, SHIFT_HISTORY)
-- ============================================================================

-- 4. Tabel SHIFT_SCHEDULES (Jadwal Shift Harian)
-- Catatan: user_id boleh NULL saat status masih 'OPEN' (menunggu di-claim karyawan)
CREATE TABLE SHIFT_SCHEDULES (
    schedule_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    outlet_id       NUMBER NOT NULL,
    template_id     NUMBER NOT NULL,
    user_id         NUMBER NULL,
    tanggal_shift   DATE NOT NULL,
    status          VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_sched_outlet FOREIGN KEY (outlet_id) REFERENCES OUTLETS(outlet_id),
    CONSTRAINT fk_sched_template FOREIGN KEY (template_id) REFERENCES SHIFT_TEMPLATES(template_id),
    CONSTRAINT fk_sched_user FOREIGN KEY (user_id) REFERENCES USERS(user_id),
    CONSTRAINT chk_sched_status CHECK (status IN ('OPEN', 'ASSIGNED', 'SWAP_PENDING', 'COMPLETED', 'CANCELLED'))
);

-- 5. Tabel SHIFT_SWAPS (Pengajuan Tukar Shift Antar Karyawan)
CREATE TABLE SHIFT_SWAPS (
    swap_id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_asal_id    NUMBER NOT NULL,
    schedule_tujuan_id  NUMBER NOT NULL,
    pengaju_id          NUMBER NOT NULL,
    penerima_id         NUMBER NOT NULL,
    status_swap         VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    alasan              VARCHAR2(255),
    created_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at          TIMESTAMP,
    CONSTRAINT fk_swap_sched_asal FOREIGN KEY (schedule_asal_id) REFERENCES SHIFT_SCHEDULES(schedule_id),
    CONSTRAINT fk_swap_sched_tujuan FOREIGN KEY (schedule_tujuan_id) REFERENCES SHIFT_SCHEDULES(schedule_id),
    CONSTRAINT fk_swap_pengaju FOREIGN KEY (pengaju_id) REFERENCES USERS(user_id),
    CONSTRAINT fk_swap_penerima FOREIGN KEY (penerima_id) REFERENCES USERS(user_id),
    CONSTRAINT chk_swap_status CHECK (status_swap IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT chk_swap_diff_user CHECK (pengaju_id <> penerima_id)
);

-- 6. Tabel SHIFT_HISTORY (Audit Log Perubahan Jadwal Shift)
CREATE TABLE SHIFT_HISTORY (
    history_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id     NUMBER NOT NULL,
    user_lama_id    NUMBER NULL,
    user_baru_id    NUMBER NULL,
    aksi            VARCHAR2(50) NOT NULL,
    keterangan      VARCHAR2(255),
    waktu_perubahan TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_hist_schedule FOREIGN KEY (schedule_id) REFERENCES SHIFT_SCHEDULES(schedule_id),
    CONSTRAINT fk_hist_user_lama FOREIGN KEY (user_lama_id) REFERENCES USERS(user_id),
    CONSTRAINT fk_hist_user_baru FOREIGN KEY (user_baru_id) REFERENCES USERS(user_id)
);